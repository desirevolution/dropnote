export function translate(language: Language, message: string, values?: Record<string, string | number>): string {
  const label = language === "de" && Object.hasOwn(german, message) ? (german[message] ?? message) : message;
  return values ? label.replace(/\{(\w+)\}/g, (token, key: string) => String(values[key] ?? token)) : label;
}
